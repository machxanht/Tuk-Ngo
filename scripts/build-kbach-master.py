"""Trace the supplied graphic clip's clear closeups; never upscale old hull pixels.

Usage: python scripts/build-kbach-master.py path/to/clip.mp4
Requires the existing OpenCV/Python setup. Source video remains private/local.
"""
import argparse, hashlib, json
from pathlib import Path
import cv2

parser=argparse.ArgumentParser();parser.add_argument('video',type=Path);args=parser.parse_args()
root=Path(__file__).resolve().parent.parent
video=cv2.VideoCapture(str(args.video))
if not video.isOpened():raise RuntimeError('Cannot read source video')

def frame(seconds):
 video.set(cv2.CAP_PROP_POS_MSEC,seconds*1000);ok,image=video.read()
 if not ok:raise RuntimeError(f'Missing frame at {seconds}s')
 if image.shape[:2]!=(398,872):raise RuntimeError('Source registration expects the supplied 872 x 398 clip')
 return image

def contour_path(mask):
 # Work at source resolution: soften the threshold edge before contouring,
 # then retain subpixel coordinates. No neural/generative detail is invented.
 mask=cv2.resize(mask,None,fx=2,fy=2,interpolation=cv2.INTER_LINEAR)
 _,mask=cv2.threshold(mask,127,255,cv2.THRESH_BINARY)
 contours,_=cv2.findContours(mask,cv2.RETR_LIST,cv2.CHAIN_APPROX_SIMPLE)
 paths=[]
 for contour in contours:
  if abs(cv2.contourArea(contour))<2:continue
  points=cv2.approxPolyDP(contour,.55,True).reshape(-1,2).astype(float)/2
  if len(points)<3:continue
  previous=(points[-1]+points[0])/2
  number=lambda value:f'{value:.2f}'.rstrip('0').rstrip('.')
  path=f'M{number(previous[0])},{number(previous[1])}'
  for i,p in enumerate(points):
   end=(p+points[(i+1)%len(points)])/2
   control=p-previous;delta=end-previous
   path+='q'+','.join(map(number,control))+' '+','.join(map(number,delta))
   previous=end
  paths.append(path+'Z')
 return ''.join(paths)

def trace(image):
 hsv=cv2.cvtColor(image,cv2.COLOR_BGR2HSV)
 # Separate the bright gold fill from the dark engraved veins as well as black.
 gold=cv2.inRange(hsv,(15,85,185),(48,255,255))
 red=cv2.bitwise_or(cv2.inRange(hsv,(0,130,90),(12,255,255)),cv2.inRange(hsv,(170,130,90),(179,255,255)))
 return {'width':image.shape[1],'height':image.shape[0],'gold':contour_path(gold),'red':contour_path(red)}

# Complete two-flower/large-small-leaf repeat and the clear diagonal panel.
# The large curl is taken from the same closeup, preserving its fine dark veins.
# The lower design and measurement labels are excluded.
center=frame(56)[72:302,222:524]
transition=frame(68)[110:330,:]
end=frame(68)[110:263,38:243]
data={'sourceSha256':hashlib.sha256(args.video.read_bytes()).hexdigest(),'sourceSize':[872,398],'framesSeconds':{'center':56,'transition':68,'end':68},'method':'source contour paths with quadratic edge smoothing; no generated ornament','center':trace(center),'transition':trace(transition),'end':trace(end)}
destination=root/'src/race/kbach-motifs.mjs'
destination.write_text('// Generated by scripts/build-kbach-master.py from the owner-supplied graphic clip.\nexport const kbachMotifs='+json.dumps(data,separators=(',',':'))+';\n',encoding='utf-8',newline='\n')
video.release();print(json.dumps({'output':str(destination),'bytes':destination.stat().st_size,'sourceSha256':data['sourceSha256']}))
